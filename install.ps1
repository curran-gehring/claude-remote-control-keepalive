<#
.SYNOPSIS
  Install the Claude Remote Control Keepalive watchdog as a scheduled task.

.DESCRIPTION
  Copies the watchdog into %USERPROFILE%\.claude-rc-keepalive\, writes your config,
  and registers a scheduled task that keeps a `claude remote-control` server running
  so this machine is always available in claude.ai/code and the Claude mobile app.

  Run this in an ELEVATED PowerShell (Run as administrator).

.PARAMETER Name
  Name shown for this machine in claude.ai/code and the app. Default: computer name.

.PARAMETER WorkDir
  Directory new remote sessions open in. Default: your user profile. (e.g. -WorkDir C:\Dev)

.PARAMETER PermissionMode
  Permission mode for spawned sessions: default | acceptEdits | bypassPermissions |
  plan | dontAsk | auto. Default: default. ('bypassPermissions' = no prompts; powerful.)

.PARAMETER WhetherLoggedOn
  Also run BEFORE you log in (covers unattended reboots). Requires your Windows
  account PASSWORD (Task Scheduler stores it encrypted). A Windows Hello PIN will
  NOT work. Without this switch the task runs at logon, which is enough if you stay
  logged in.

.EXAMPLE
  .\install.ps1 -Name "Dev" -WorkDir C:\Dev

.EXAMPLE
  .\install.ps1 -Name "Dev" -WorkDir C:\Dev -PermissionMode bypassPermissions -WhetherLoggedOn
#>
[CmdletBinding()]
param(
    [string]$Name = $env:COMPUTERNAME,
    [string]$WorkDir = $env:USERPROFILE,
    [ValidateSet('default','acceptEdits','bypassPermissions','plan','dontAsk','auto')]
    [string]$PermissionMode = 'default',
    [switch]$WhetherLoggedOn
)
$ErrorActionPreference = 'Stop'
$taskName = 'Claude Remote Control Keepalive'

$isAdmin = ([Security.Principal.WindowsPrincipal][Security.Principal.WindowsIdentity]::GetCurrent()
           ).IsInRole([Security.Principal.WindowsBuiltinRole]::Administrator)
if (-not $isAdmin) {
    Write-Host 'ERROR: Run this in an ELEVATED PowerShell (Run as administrator).' -ForegroundColor Red
    exit 1
}
if (-not (Get-Command claude -ErrorAction SilentlyContinue)) {
    Write-Host 'ERROR: the `claude` CLI is not on PATH. Install Claude Code first.' -ForegroundColor Red
    exit 1
}

# --- copy files into a stable location ---
$installDir = Join-Path $env:USERPROFILE '.claude-rc-keepalive'
New-Item -ItemType Directory -Force $installDir | Out-Null
$srcDir = Join-Path $PSScriptRoot 'scripts'
Copy-Item (Join-Path $srcDir 'rc-watchdog.ps1') $installDir -Force
Copy-Item (Join-Path $srcDir 'run-hidden.vbs')  $installDir -Force

# --- write config ---
$cfg = @"
# Generated by install.ps1 on $(Get-Date -Format 'yyyy-MM-dd'). Edit to taste.
`$RcName         = '$Name'
`$WorkDir        = '$($WorkDir -replace "'","''")'
`$PermissionMode = '$PermissionMode'
"@
Set-Content -Path (Join-Path $installDir 'config.ps1') -Value $cfg -Encoding UTF8

# --- build and register the scheduled task ---
$vbs = Join-Path $installDir 'run-hidden.vbs'
$ps1 = Join-Path $installDir 'rc-watchdog.ps1'
$action  = New-ScheduledTaskAction -Execute 'wscript.exe' -Argument ('"{0}" "{1}"' -f $vbs, $ps1)
$repeat  = New-ScheduledTaskTrigger -Once -At (Get-Date) `
              -RepetitionInterval (New-TimeSpan -Minutes 5) -RepetitionDuration (New-TimeSpan -Days 3650)
$settings = New-ScheduledTaskSettingsSet -MultipleInstances IgnoreNew -StartWhenAvailable `
              -ExecutionTimeLimit (New-TimeSpan -Minutes 5) -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries

if ($WhetherLoggedOn) {
    $startup = New-ScheduledTaskTrigger -AtStartup
    $cred = Get-Credential -UserName "$env:USERDOMAIN\$env:USERNAME" `
        -Message 'Windows account PASSWORD (stored encrypted so the task can run before login). A Windows Hello PIN will NOT work.'
    try {
        Register-ScheduledTask -TaskName $taskName -Action $action -Trigger @($startup,$repeat) `
            -Settings $settings -User $cred.UserName -Password $cred.GetNetworkCredential().Password `
            -RunLevel Limited -Force | Out-Null
    } catch {
        Write-Host "Registration failed: $($_.Exception.Message)" -ForegroundColor Red
        Write-Host "On Microsoft Entra / Azure AD accounts, try your full UPN (you@domain.com) as the username, and make sure you typed the account PASSWORD, not the PIN." -ForegroundColor Yellow
        exit 1
    }
} else {
    $logon = New-ScheduledTaskTrigger -AtLogOn
    Register-ScheduledTask -TaskName $taskName -Action $action -Trigger @($logon,$repeat) `
        -Settings $settings -RunLevel Limited -Force | Out-Null
}

Start-ScheduledTask -TaskName $taskName
Write-Host ""
Write-Host "Installed '$taskName'." -ForegroundColor Green
Write-Host "  name           : $Name"
Write-Host "  work directory : $WorkDir"
Write-Host "  permission mode: $PermissionMode"
Write-Host "  trigger        : $(if ($WhetherLoggedOn) {'at startup + every 5 min, whether logged on or not'} else {'at logon + every 5 min'})"
Write-Host ""
Write-Host "Within ~30s, '$Name' should appear in claude.ai/code and the Claude app." -ForegroundColor Cyan
Write-Host "Watchdog log: $installDir\state\rc-watchdog.log"
